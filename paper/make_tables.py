"""Generate paper/cert_table.tex from certificate/445466268731.txt (run from the paper/ folder)."""
from pathlib import Path

rows = []
for line in Path("../certificate/445466268731.txt").read_text().splitlines():
    if line.startswith("#") or not line.strip():
        continue
    x, y, p, q = line.split()
    assert int(p) == 445466268731 - 2 ** int(x) - 7 * 2 ** int(y) and int(p) % int(q) == 0 and int(p) % 6 == 1
    rows.append((int(x), int(y), int(q)))
assert len(rows) == 342
rows.sort()
cols = 6
per = -(-len(rows) // cols)
out = ["% generated by make_tables.py -- do not edit", "\\begin{tabular}{" + "rrr@{\\qquad}" * (cols - 1) + "rrr}", "\\toprule",
       " & ".join(["$x$ & $y$ & $q$"] * cols) + " \\\\", "\\midrule"]
for i in range(per):
    cells = []
    for c in range(cols):
        k = c * per + i
        cells.append(f"{rows[k][0]} & {rows[k][1]} & {rows[k][2]}" if k < len(rows) else " & & ")
    out.append(" & ".join(cells) + " \\\\")
out += ["\\bottomrule", "\\end{tabular}"]
Path("cert_table.tex").write_text("\n".join(out) + "\n")
print(len(rows), "rows; largest least factor", max(r[2] for r in rows))
